def test_an_unknown_choice_is_rejected(store):
    """'maybe', 'skip', 'Left' — anything outside the three is a bug upstream,
    and the store is the last place it can be caught before it is permanent."""
    for bad in ("maybe", "skip", "Left", "", "LEFT"):
        with pytest.raises(InvalidChoiceError):
            store.add_label("p0001", "A1", bad)
    assert store.count() == 0


def test_one_labeller_cannot_label_the_same_pair_twice(store):
    """This is what makes kappa mean anything.

    Cohen's kappa compares two *independent* opinions. If one person could
    answer the same pair twice, the double-labelled set could silently contain
    one person agreeing with themselves, and kappa would report inter-annotator
    agreement that was never measured.
    """
    store.add_label("p0001", "A1", "left")
    with pytest.raises(DuplicateLabelError):
        store.add_label("p0001", "A1", "right")
    assert store.labels_for_pair("p0001")[0]["choice"] == "left"


def test_two_labellers_may_label_the_same_pair(store):
    """The 50 double-labelled pairs depend on exactly this being allowed."""
    store.add_label("p0001", "A1", "left")
    store.add_label("p0001", "A2", "right")
    assert len(store.labels_for_pair("p0001")) == 2


def test_the_check_constraint_is_in_the_schema_not_only_in_python(store, tmp_path):
    """Defence in depth: Diya's UI writes to this file too, and it will not be
    going through this Python class. The CHECK must hold against raw SQL."""
    raw = sqlite3.connect(tmp_path / "labels.db")
    with pytest.raises(sqlite3.IntegrityError):
        raw.execute(
            "INSERT INTO labels (pair_id, labeller_id, choice, created_at) "
            "VALUES ('p0002', 'A1', 'maybe', '2026-09-04T00:00:00Z')"
        )
    raw.close()


def test_the_unique_constraint_is_in_the_schema_not_only_in_python(store, tmp_path):
    store.add_label("p0001", "A1", "left")
    raw = sqlite3.connect(tmp_path / "labels.db")
    with pytest.raises(sqlite3.IntegrityError):
        raw.execute(
            "INSERT INTO labels (pair_id, labeller_id, choice, created_at) "
            "VALUES ('p0001', 'A1', 'right', '2026-09-04T00:00:00Z')"
        )
    raw.close()


# --------------------------------------------------------------------------
# CONSTRAINTS #23 — labels carry an opaque id, a choice and a timestamp
# --------------------------------------------------------------------------

def test_the_schema_holds_no_field_that_could_identify_a_person(store, tmp_path):
    """CONSTRAINTS #23. If practitioner labels come via Diya's KPMG contacts,
    nothing client- or company-identifying may enter this repository. The
    enforcement is that there is nowhere to put it: the columns are fixed and
    this test fails the moment someone adds `name`, `email` or `employer`.
    """
    raw = sqlite3.connect(tmp_path / "labels.db")
    columns = {row[1] for row in raw.execute("PRAGMA table_info(labels)")}
    raw.close()
    assert columns == {
        "id", "pair_id", "labeller_id", "choice", "created_at", "seconds_taken",
    }


def test_seconds_taken_may_be_null_rather_than_invented(store):
    """A CLI labeller may not measure it. A silently-invented 0.0 would look
    like an instant judgement and would poison any later 'how long did people
    think about this' analysis."""
    store.add_label("p0001", "A1", "tie")
    assert store.labels_for_pair("p0001")[0]["seconds_taken"] is None


def test_created_at_is_written_automatically_in_utc(store):
    store.add_label("p0001", "A1", "left")
    stamp = store.labels_for_pair("p0001")[0]["created_at"]
    assert stamp.endswith("Z"), f"not a UTC ISO-8601 stamp: {stamp}"
    assert stamp[:2] == "20"


def test_created_at_can_be_supplied_for_reproducible_tests(store):
    store.add_label("p0001", "A1", "left", created_at="2026-09-04T12:00:00Z")
    assert store.labels_for_pair("p0001")[0]["created_at"] == "2026-09-04T12:00:00Z"


