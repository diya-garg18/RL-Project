"""`rlhf.store` — the SQLite the human labels land in.

This is the least replaceable artefact in the project: 300 pairs at ~20 seconds
each is ~100 minutes of human time that cannot be regenerated by re-running a
script (PROJECT_BRIEF §6.2, and the note in `.gitignore`). So the tests here are
mostly about refusing to accept data that would quietly corrupt it — a third
choice value, a second opinion from the same person on the same pair — rather
than about the happy path.

Every store in this file is a temporary file, never `results/rlhf/labels.db`.
"""

import sqlite3
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from soc_triage.rlhf.store import (  # noqa: E402
    CHOICES,
    DuplicateLabelError,
    InvalidChoiceError,
    LabelStore,
)


@pytest.fixture
def store(tmp_path):
    with LabelStore(tmp_path / "labels.db") as s:
        yield s


# --------------------------------------------------------------------------
# The happy path, briefly
# --------------------------------------------------------------------------

def test_a_label_survives_a_round_trip(store):
    store.add_label("p0001", "A1", "left", seconds_taken=18.5)
    rows = store.labels_for_pair("p0001")
    assert len(rows) == 1
    assert rows[0]["labeller_id"] == "A1"
    assert rows[0]["choice"] == "left"
    assert rows[0]["seconds_taken"] == 18.5


def test_the_three_choices_are_left_right_and_tie(store):
    """PROJECT_BRIEF §6.2: the labeller clicks left / right / can't tell."""
    assert set(CHOICES) == {"left", "right", "tie"}
    for i, choice in enumerate(CHOICES):
        store.add_label(f"p{i:04d}", "A1", choice)
    assert store.count() == 3


def test_the_database_persists_across_connections(tmp_path):
    """A labelling session is a person closing a laptop, not one process run."""
    path = tmp_path / "labels.db"
    with LabelStore(path) as first:
        first.add_label("p0001", "A1", "right")
    with LabelStore(path) as second:
        assert second.count() == 1
        assert second.labels_for_pair("p0001")[0]["choice"] == "right"


