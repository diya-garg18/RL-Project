def test_labels_by_returns_only_that_labeller(store):
    store.add_label("p0001", "A1", "left")
    store.add_label("p0002", "A1", "right")
    store.add_label("p0001", "A2", "tie")
    assert {r["pair_id"] for r in store.labels_by("A1")} == {"p0001", "p0002"}
    assert {r["pair_id"] for r in store.labels_by("A2")} == {"p0001"}


def test_labellers_lists_who_has_contributed(store):
    store.add_label("p0001", "A1", "left")
    store.add_label("p0001", "A2", "left")
    store.add_label("p0002", "A1", "left")
    assert store.labellers() == ["A1", "A2"]


def test_an_empty_store_reports_zero_rather_than_failing(store):
    assert store.count() == 0
    assert store.labellers() == []
    assert store.labels_for_pair("p0001") == []
    assert store.all_labels() == []


