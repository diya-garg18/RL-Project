def test_export_csv_writes_every_row_with_a_header(store, tmp_path):
    """`.gitignore` tells the reader to keep a CSV export beside the database
    because the file is gitignored and irreplaceable. That export has to exist."""
    store.add_label("p0001", "A1", "left", seconds_taken=12.0,
                    created_at="2026-09-04T12:00:00Z")
    store.add_label("p0002", "A2", "tie", created_at="2026-09-04T12:01:00Z")

    out = tmp_path / "labels.csv"
    store.export_csv(out)
    lines = out.read_text(encoding="utf-8").strip().splitlines()

    assert lines[0] == "id,pair_id,labeller_id,choice,created_at,seconds_taken"
    assert len(lines) == 3
    assert lines[1] == "1,p0001,A1,left,2026-09-04T12:00:00Z,12.0"
    assert lines[2] == "2,p0002,A2,tie,2026-09-04T12:01:00Z,"


def test_export_csv_of_an_empty_store_still_writes_the_header(store, tmp_path):
    out = tmp_path / "labels.csv"
    store.export_csv(out)
    assert out.read_text(encoding="utf-8").strip() == (
        "id,pair_id,labeller_id,choice,created_at,seconds_taken"
    )


def test_the_store_creates_its_parent_directory(tmp_path):
    """`results/rlhf/` does not exist on a fresh clone — results/ is gitignored."""
    path = tmp_path / "does" / "not" / "exist" / "labels.db"
    with LabelStore(path) as s:
        s.add_label("p0001", "A1", "left")
    assert path.exists()
